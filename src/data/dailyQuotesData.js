/**
 * Lấy câu châm ngôn tương ứng với ngày trong năm (xoay vòng tự động mỗi ngày 1 câu).
 * Đảm bảo mọi người dùng truy cập trong cùng 1 ngày lịch sẽ xem cùng 1 câu.
 * @param {Date|string} [targetDate] - Ngày chỉ định (mặc định hôm nay)
 * @returns {typeof DAILY_QUOTES[0]}
 */
export function getDailyQuote(targetDate = new Date()) {
  const d = targetDate instanceof Date ? targetDate : new Date(targetDate);
  const validDate = isNaN(d.getTime()) ? new Date() : d;

  // Tính số ngày trong năm (Day of Year: 0 -> 365)
  const startOfYear = new Date(validDate.getFullYear(), 0, 1);
  const diffTime = validDate.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diffTime / (1000 * 60 * 60 * 24));

  const index = Math.abs(dayOfYear) % DAILY_QUOTES.length;
  return DAILY_QUOTES[index];
}

/**
 * Lấy một câu châm ngôn ngẫu nhiên khác với câu hiện tại
 * @param {number} [excludeId]
 * @returns {typeof DAILY_QUOTES[0]}
 */
export function getRandomQuote(excludeId = null) {
  const pool = excludeId ? DAILY_QUOTES.filter(q => q.id !== excludeId) : DAILY_QUOTES;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex] || DAILY_QUOTES[0];
}

