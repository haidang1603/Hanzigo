export const HANZIGO_LIBRARY_CATALOG = [
  ...GRAMMAR_METADATA,
  ...PRACTICAL_METADATA,
  ...EXTERNAL_METADATA,
];

export const VERIFIED_EXTERNAL_CATALOG = EXTERNAL_METADATA;

const packCache = new Map();
const detailCache = new Map();

async function loadPackByKey(packKey) {
  if (packCache.has(packKey)) {
    return packCache.get(packKey);
  }
  let items = [];
  if (packKey === 'grammar') {
    const mod = await import('./grammarCompendium.js');
    items = mod.GRAMMAR_COMPENDIUM_PACK || [];
  } else if (packKey === 'practical') {
    const mod = await import('./practicalGuides.js');
    items = mod.PRACTICAL_GUIDES_PACK || [];
  } else if (packKey === 'external') {
    const mod = await import('./verifiedExternalResources.js');
    items = mod.VERIFIED_EXTERNAL_RESOURCES || [];
  }
  packCache.set(packKey, items);
  items.forEach((item) => {
    detailCache.set(item.id, item);
  });
  return items;
}

export async function loadMaterialDetailById(id) {
  if (!id) return null;
  if (detailCache.has(id)) {
    return detailCache.get(id);
  }
  const meta = HANZIGO_LIBRARY_CATALOG.find((m) => m.id === id);
  if (!meta) return null;
  await loadPackByKey(meta.packKey);
  return detailCache.get(id) || meta;
}

export async function loadAllStructuredMaterials() {
  const [grammar, practical, external] = await Promise.all([
    loadPackByKey('grammar'),
    loadPackByKey('practical'),
    loadPackByKey('external'),
  ]);
  return [...grammar, ...practical, ...external];
}
